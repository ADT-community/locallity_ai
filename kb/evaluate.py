"""Record retrieval results for ten representative farmer questions."""

import json
import os

from .search import get_kb

QUESTIONS_FILE = os.path.join(os.path.dirname(__file__), "evaluation", "questions.json")
RESULTS_FILE = os.path.join(os.path.dirname(__file__), "evaluation", "retrieval_results.md")


def load_questions():
    with open(QUESTIONS_FILE, encoding="utf-8") as handle:
        return json.load(handle)["questions"]


def write_results(path=RESULTS_FILE, k=5):
    """Run real retrieval and write a human-readable evidence file."""
    kb = get_kb()
    questions = load_questions()
    lines = [
        "# Retrieval results for 10 test questions",
        "",
        "Generated by `python -m kb eval` from the committed index using "
        "`search(question, k=5)`. Each row is a real result, not a mock.",
        "",
    ]
    for number, item in enumerate(questions, 1):
        question = item["question"]
        lines.extend(["## %d. %s" % (number, question), "",
                      "Expected topic: %s" % item["topic"], "",
                      "| # | Source | Country | Score | Passage |",
                      "|---|--------|---------|-------|---------|"])
        for rank, result in enumerate(kb.search(question, k=k), 1):
            passage = result["passage"].replace("|", "\\|").replace("\n", " ")
            lines.append("| %d | [%s](%s) | %s | %.4f | %s… |" % (
                rank, result["title"], result["url"], result["country"],
                result["score"], passage[:140]))
        lines.append("")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return path
